# 2. Câu 8: 3 trục số giao P và Q
fig, axes = plt.subplots(3, 1, figsize=(6.5, 3.2), dpi=220)
labels = ['P = (-2; 5)', 'Q = (0; +∞)', 'P ∩ Q = (0; 5)']
for i, ax in enumerate(axes):
    ax.set_xlim(-4, 8)
